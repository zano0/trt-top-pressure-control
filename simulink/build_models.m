function build_models()
%BUILD_MODELS Generate trt_model.slx programmatically (reproducible, reviewable in git diffs).
%
%   Top level:  Scenario -> Plant <-> PLC controller (Ts = 100 ms) -> logging
%   Plant:      Actuators | Turbine + ESD (Stodola) and bypass (ISA-75.01) | two-volume mass
%               balance V1 (top) - gas cleaning - V2 (header) | Rotor + generator | Transmitters
%   The physics lives in plain .m functions (plant_*.m, trt_flow.m, bp_flow.m) called from
%   MATLAB Function blocks; the mass balances are drawn with Sum/Gain/Integrator blocks.
%   The PLC logic is trt_controller_step.m, the same file Simulink PLC Coder translates to ST.
%
%   Workspace variables used by the model: P (params), C (controller_config), X0 (steady_state),
%   SCN (scenario matrix, see make_scenario.m).

mdl  = 'trt_model';
here = fileparts(mfilename('fullpath'));
if bdIsLoaded(mdl), close_system(mdl, 0); end
f = fullfile(here, [mdl '.slx']);
if exist(f, 'file'), delete(f); end
new_system(mdl);
set_param(mdl, 'Solver', 'ode4', 'FixedStep', 'P.dt_sim', 'StopTime', '100', ...
    'SaveTime', 'off', 'SaveOutput', 'off', 'SaveState', 'off', 'SignalLogging', 'off', ...
    'ReturnWorkspaceOutputs', 'on', 'AlgebraicLoopMsg', 'error');

%% ---------------- Top level ----------------
add_block('simulink/Sources/From Workspace', [mdl '/Scenario'], 'VariableName', 'SCN', ...
    'Interpolate', 'off', 'OutputAfterFinalValue', 'Holding final value', 'SampleTime', 'C.Ts', ...
    'Position', [30 190 110 230]);
add_block('simulink/Ports & Subsystems/Subsystem', [mdl '/Plant'], 'Position', [250 160 400 260]);
add_block('simulink/Ports & Subsystems/Subsystem', [mdl '/PLC controller (Ts = 100 ms)'], ...
    'Position', [250 20 400 110]);
add_block('simulink/Signal Routing/Mux', [mdl '/LogMux'], 'Inputs', '4', 'Position', [520 120 530 260]);
add_block('simulink/Sinks/To Workspace', [mdl '/LOG'], 'VariableName', 'LOG', ...
    'SaveFormat', 'Structure With Time', 'SampleTime', '0.05', 'Position', [580 175 650 205]);

build_plant([mdl '/Plant']);
build_plc([mdl '/PLC controller (Ts = 100 ms)']);

% one-scan output delay: inputs read at scan start, outputs written at scan end
add_block('simulink/Discrete/Unit Delay', [mdl '/PLC output update (1 scan)'], 'InitialCondition', 'C.init.cmd', ...
    'SampleTime', 'C.Ts', 'Position', [440 40 480 80]);
ctl = 'PLC controller (Ts = 100 ms)';
DL  = 'PLC output update (1 scan)';
add_line(mdl, 'Scenario/1', 'Plant/2', 'autorouting', 'on');
add_line(mdl, 'Scenario/1', [ctl '/2'], 'autorouting', 'on');
add_line(mdl, [ctl '/1'], [DL '/1'], 'autorouting', 'on');
add_line(mdl, [DL '/1'], 'Plant/1', 'autorouting', 'on');
add_line(mdl, 'Plant/1', [ctl '/1'], 'autorouting', 'on');
add_line(mdl, 'Plant/2', 'LogMux/1', 'autorouting', 'on');
add_line(mdl, [DL '/1'], 'LogMux/2', 'autorouting', 'on');
add_line(mdl, [ctl '/2'], 'LogMux/3', 'autorouting', 'on');
add_line(mdl, 'Plant/1', 'LogMux/4', 'autorouting', 'on');
add_line(mdl, 'LogMux/1', 'LOG/1');

add_block('built-in/Note', [mdl '/note'], 'Position', [30 300], 'Text', ...
    sprintf(['TRT top-pressure control - generated by build_models.m\n' ...
             'Independent educational project, illustrative parameters (see docs/assumptions.md)']));

save_system(mdl, f);
% diagram snapshots for the documentation
res = fullfile(here, 'results');
if ~exist(res, 'dir'), mkdir(res); end
try
    print(['-s' mdl], '-dpng', '-r150', fullfile(res, 'model_top.png'));
catch err
    warning('Diagram export skipped: %s', err.message);
end
close_system(mdl);
fprintf('Built %s\n', f);
end

%% =====================================================================
function build_plant(s)
delete_default(s);
add_block('simulink/Sources/In1', [s '/cmd'], 'Position', [20 40 50 54]);
add_block('simulink/Sources/In1', [s '/scn'], 'Position', [20 320 50 334]);
add_block('simulink/Sinks/Out1', [s '/meas'], 'Position', [1180 300 1210 314]);
add_block('simulink/Sinks/Out1', [s '/log'], 'Position', [1180 420 1210 434]);

% Actuators
mfb([s '/Actuators'], ...
    "function xadot = f(cmd, xa, P)" + newline + "xadot = plant_actuators(cmd, xa, P);", {'P'}, [120 30 260 90]);
add_block('simulink/Continuous/Integrator', [s '/Actuator positions'], 'InitialCondition', 'X0.xa', ...
    'LimitOutput', 'on', 'UpperSaturationLimit', '1', 'LowerSaturationLimit', '0', 'Position', [300 45 330 75]);
% Flows
mfb([s '/Turbine+ESD (Stodola), bypass (ISA-75.01)'], ...
    "function [m_trt, m_bp, P_turb, p_in] = f(xa, ph, P)" + newline + ...
    "[m_trt, m_bp, P_turb, p_in] = plant_flows(xa, ph, P);", {'P'}, [400 40 600 160]);
% Blast flow (disturbance) from the scenario
mfb([s '/Blast-furnace gas flow'], "function m_in = f(scn)" + newline + "m_in = scn(1);", {}, [120 300 260 340]);
% Two-volume mass balance with plain blocks: V1 (top) -- cleaning resistance -- V2 (header)
mfb([s '/Gas cleaning (dp = k m^2)'], ...
    "function m_c = f(p1, ph, P)" + newline + "m_c = plant_cleaning(p1, ph, P);", {'P'}, [300 200 440 250]);
add_block('simulink/Math Operations/Sum', [s '/Mass balance V1'], 'Inputs', '+-', 'Position', [520 300 540 340]);
add_block('simulink/Math Operations/Gain', [s '/1 over C1'], 'Gain', '1/P.C1', 'Position', [570 305 620 335]);
add_block('simulink/Continuous/Integrator', [s '/Top pressure p1'], 'InitialCondition', 'X0.p1', ...
    'Position', [650 305 680 335]);
add_block('simulink/Math Operations/Sum', [s '/Sum bypass'], 'Inputs', '+', 'Position', [660 90 680 110]);
add_block('simulink/Math Operations/Sum', [s '/Mass balance V2'], 'Inputs', '+--', 'Position', [720 200 740 260]);
add_block('simulink/Math Operations/Gain', [s '/1 over C2'], 'Gain', '1/P.C2', 'Position', [770 215 830 245]);
add_block('simulink/Continuous/Integrator', [s '/Header pressure p_h'], 'InitialCondition', 'X0.ph', ...
    'Position', [860 215 890 245]);
% Rotor
mfb([s '/Rotor + generator (CB-101)'], ...
    "function [wdot, P_el, cb] = f(P_turb, w, cmd, scn, P)" + newline + ...
    "[wdot, P_el, cb] = plant_rotor(P_turb, w, cmd, scn, P);", {'P'}, [660 380 820 480]);
add_block('simulink/Continuous/Integrator', [s '/Rotor speed'], 'InitialCondition', 'X0.w', ...
    'Position', [860 390 890 420]);
% Transmitters (first-order lags PT-100A/B/C)
mfb([s '/Transmitter lags'], ...
    "function xdot = f(p_top, xpt, P)" + newline + "xdot = (p_top - xpt) / P.pt.tau;", {'P'}, [930 360 1060 400]);
add_block('simulink/Continuous/Integrator', [s '/PT-100 states'], 'InitialCondition', 'X0.xpt', ...
    'Position', [1080 365 1110 395]);
% Measurements and log vector
mfb([s '/Measurements'], ...
    "function meas = f(xpt, scn, ph, xa, P_el, cb, w, P)" + newline + ...
    "meas = plant_meas(xpt, scn, ph, xa, P_el, cb, w, P);", {'P'}, [1000 440 1130 560]);
mfb([s '/Log vector'], ...
    "function y = f(p_top, ph, m_in, m_trt, m_bp, P_turb, P_el, w, xa, p_in, cb, m_c)" + newline + ...
    "y = [p_top; ph; m_in; m_trt; m_bp(1); m_bp(2); P_turb; P_el; w; xa(1); xa(2); xa(3); xa(4); p_in; cb; m_c];", ...
    {}, [1000 600 1130 760]);

A  = 'Actuators';  IA = 'Actuator positions';  F = 'Turbine+ESD (Stodola), bypass (ISA-75.01)';
BF = 'Blast-furnace gas flow';  PH = 'Header pressure p_h';  GC = 'Gas cleaning (dp = k m^2)';
TP = 'Top pressure p1';  RO = 'Rotor + generator (CB-101)';  RS = 'Rotor speed';
TL = 'Transmitter lags';  PS = 'PT-100 states';  ME = 'Measurements';  LV = 'Log vector';
L = @(a, b) add_line(s, a, b, 'autorouting', 'smart');
L('cmd/1', [A '/1']);           L([IA '/1'], [A '/2']);     L([A '/1'], [IA '/1']);
L([IA '/1'], [F '/1']);         L([PH '/1'], [F '/2']);
L('scn/1', [BF '/1']);
L([TP '/1'], [GC '/1']);        L([PH '/1'], [GC '/2']);
L([BF '/1'], 'Mass balance V1/1');  L([GC '/1'], 'Mass balance V1/2');
L('Mass balance V1/1', '1 over C1/1');  L('1 over C1/1', [TP '/1']);
L([GC '/1'], 'Mass balance V2/1');  L([F '/1'], 'Mass balance V2/2');  L([F '/2'], 'Sum bypass/1');
L('Sum bypass/1', 'Mass balance V2/3');  L('Mass balance V2/1', '1 over C2/1');  L('1 over C2/1', [PH '/1']);
L([F '/3'], [RO '/1']);         L([RS '/1'], [RO '/2']);    L('cmd/1', [RO '/3']);   L('scn/1', [RO '/4']);
L([RO '/1'], [RS '/1']);
L([TP '/1'], [TL '/1']);        L([PS '/1'], [TL '/2']);    L([TL '/1'], [PS '/1']);
L([PS '/1'], [ME '/1']);        L('scn/1', [ME '/2']);      L([PH '/1'], [ME '/3']);  L([IA '/1'], [ME '/4']);
L([RO '/2'], [ME '/5']);        L([RO '/3'], [ME '/6']);    L([RS '/1'], [ME '/7']);
L([ME '/1'], 'meas/1');
L([TP '/1'], [LV '/1']);        L([PH '/1'], [LV '/2']);    L([BF '/1'], [LV '/3']);  L([F '/1'], [LV '/4']);
L([F '/2'], [LV '/5']);         L([F '/3'], [LV '/6']);     L([RO '/2'], [LV '/7']);  L([RS '/1'], [LV '/8']);
L([IA '/1'], [LV '/9']);        L([F '/4'], [LV '/10']);    L([RO '/3'], [LV '/11']);  L([GC '/1'], [LV '/12']);
L([LV '/1'], 'log/1');
end

%% =====================================================================
function build_plc(s)
delete_default(s);
set_param(s, 'TreatAsAtomicUnit', 'on', 'SystemSampleTime', 'C.Ts');
add_block('simulink/Sources/In1', [s '/meas'], 'Position', [20 40 50 54]);
add_block('simulink/Sources/In1', [s '/scn'], 'Position', [20 100 50 114]);
mfb([s '/TRT control logic'], ...
    "function [cmd, dg] = f(meas, scn, C)" + newline + "[cmd, dg] = trt_controller_step(meas, scn, C);", ...
    {'C'}, [110 30 290 130]);
add_block('simulink/Sinks/Out1', [s '/cmd'], 'Position', [430 53 460 67]);
add_block('simulink/Sinks/Out1', [s '/dg'], 'Position', [430 113 460 127]);
add_line(s, 'meas/1', 'TRT control logic/1');
add_line(s, 'scn/1', 'TRT control logic/2');
add_line(s, 'TRT control logic/1', 'cmd/1');
add_line(s, 'TRT control logic/2', 'dg/1');
end

%% =====================================================================
function mfb(path, code, params, pos)
%MFB Add a MATLAB Function block with the given code; mark listed arguments as parameters.
add_block('simulink/User-Defined Functions/MATLAB Function', path, 'Position', pos);
ch = sfroot().find('-isa', 'Stateflow.EMChart', 'Path', path);
ch.Script = char(code);
for k = 1:numel(params)
    d = ch.find('-isa', 'Stateflow.Data', 'Name', params{k});
    d.Scope = 'Parameter';
end
end

function delete_default(s)
% remove the default In1 -> Out1 of a new subsystem
lines = find_system(s, 'SearchDepth', 1, 'FindAll', 'on', 'Type', 'line');
delete_line(lines);
delete_block([s '/In1']);
delete_block([s '/Out1']);
end
